#!/usr/bin/env bash
# Command-line proof that a catalog model really splits over llama.cpp RPC.
# Usage: scripts/cli-split-check.sh <model-id> [out-dir]
#
# Runs, on this Mac, against a local ggml-rpc-server:
#   1. baseline   — single device, greedy, 16 tokens; records peak RSS
#   2. split      — same prompt with --rpc; records the per-device buffer lines
#   3. kill test  — long generation, worker killed mid-way; records what the host does
# All raw logs are written to out-dir (default: .superpowers/sdd/task/cli-split/<id>).
set -uo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
BIN="$ROOT/engine/build-cli/bin"
ID="${1:?usage: cli-split-check.sh <model-id> [out-dir]}"
OUT="${2:-$ROOT/.superpowers/sdd/task/cli-split/$ID}"
PORT="${DL_RPC_PORT:-50052}"
PROMPT="The capital of France is"
mkdir -p "$OUT"

FILE="$(python3 -I -c '
import json, sys
print(next(m["file"] for m in json.load(open(sys.argv[1])) if m["id"] == sys.argv[2]))
' "$ROOT/app/src-tauri/src/models/catalog.json" "$ID")"
MODEL="$ROOT/models/$FILE"
[[ -f "$MODEL" ]] || { echo "missing $MODEL — run scripts/fetch-model.sh $ID" >&2; exit 1; }

start_worker() {
  "$BIN/ggml-rpc-server" -H 127.0.0.1 -p "$PORT" >"$1" 2>&1 &
  WORKER_PID=$!
  for _ in $(seq 1 40); do nc -z 127.0.0.1 "$PORT" 2>/dev/null && return 0; sleep 0.25; done
  echo "worker failed to start" >&2; return 1
}
stop_worker() { kill "$WORKER_PID" 2>/dev/null; wait "$WORKER_PID" 2>/dev/null; }

# -c 4096: realistic context (the model default can be 262k); -v: print per-device and per-layer load info
COMMON=(-m "$MODEL" -ngl 99 -c 4096 -v -no-cnv -p "$PROMPT" --temp 0 --seed 1)

echo "== [$ID] 1/3 baseline (single device)"
/usr/bin/time -l "$BIN/llama-completion" "${COMMON[@]}" -n 16 \
  </dev/null >"$OUT/baseline.out" 2>"$OUT/baseline.log"
echo "exit=$?"

echo "== [$ID] 2/3 split over RPC 127.0.0.1:$PORT"
start_worker "$OUT/split-worker.log" || exit 1
"$BIN/llama-completion" "${COMMON[@]}" -n 16 --rpc "127.0.0.1:$PORT" \
  </dev/null >"$OUT/split.out" 2>"$OUT/split.log"
echo "exit=$?"
stop_worker

echo "== [$ID] 3/3 kill worker mid-generation"
start_worker "$OUT/kill-worker.log" || exit 1
"$BIN/llama-completion" "${COMMON[@]}" -n 2000 --ignore-eos --rpc "127.0.0.1:$PORT" \
  </dev/null >"$OUT/kill.out" 2>"$OUT/kill.log" &
HOST_PID=$!
# Wait until the host has produced generated text beyond the prompt, then kill the worker.
for _ in $(seq 1 240); do
  [[ $(wc -c <"$OUT/kill.out") -gt $(( ${#PROMPT} + 40 )) ]] && break
  sleep 0.25
done
echo "generated bytes before kill: $(wc -c <"$OUT/kill.out")" | tee "$OUT/kill.meta"
kill -9 "$WORKER_PID"
START=$(date +%s)
wait "$HOST_PID"; HOST_EXIT=$?
echo "host exit=$HOST_EXIT after $(( $(date +%s) - START ))s" | tee -a "$OUT/kill.meta"
wait "$WORKER_PID" 2>/dev/null
echo "logs: $OUT"
